#!/usr/bin/env python3
"""MIQP-01 contract §7.8: run the synthetic convex MIQP stratum through the
production CLI as a record separate from the linear MIP summary.

Records status, node count, reported bound, relative gap and every complete
failure exactly as measured. No speed claim and no oracle is consulted.
"""
import argparse
import hashlib
import json
import subprocess
import sys
import time
from datetime import date
from pathlib import Path


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def run_instance(solver: Path, mps: Path, time_limit: float, process_timeout: float) -> dict:
    cmd = [str(solver), str(mps), "--engine", "miqp", "--time-limit", str(time_limit)]
    started = time.perf_counter()
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=process_timeout)
    except subprocess.TimeoutExpired:
        return {"instance": mps.stem, "complete_failure": True,
                "error": f"process exceeded {process_timeout}s wall timeout"}
    wall_ms = (time.perf_counter() - started) * 1000.0
    parsed = None
    for line in proc.stdout.splitlines():
        stripped = line.strip()
        if stripped.startswith("{") and stripped.endswith("}"):
            try:
                parsed = json.loads(stripped)
                break
            except json.JSONDecodeError:
                continue
    if parsed is None:
        return {"instance": mps.stem, "exit_code": proc.returncode, "complete_failure": True,
                "error": "no JSON on stdout", "stderr_tail": proc.stderr[-300:],
                "stdout_tail": proc.stdout[-300:], "wall_ms": round(wall_ms, 3)}
    record = {
        "instance": mps.stem,
        "exit_code": proc.returncode,
        "status": parsed.get("status"),
        "stop_reason": parsed.get("stop_reason", ""),
        "assurance": parsed.get("assurance"),
        "guarantee_tier": parsed.get("guarantee_tier"),
        "proof_status": parsed.get("proof_status"),
        "problem_class": parsed.get("problem_class"),
        "rows": parsed.get("rows"),
        "cols": parsed.get("cols"),
        "nonzeros": parsed.get("nonzeros"),
        "objective": parsed.get("objective"),
        "best_bound": parsed.get("best_bound"),
        "relative_gap": parsed.get("relative_gap"),
        "nodes_explored": parsed.get("nodes_explored"),
        "lp_iterations": parsed.get("lp_iterations"),
        "cuts_generated": parsed.get("cuts_generated"),
        "runtime_ms": parsed.get("runtime_ms"),
        "wall_ms": round(wall_ms, 3),
        "complete_failure": proc.returncode != 0 and parsed.get("status") in (None, ""),
    }
    return record


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solver", required=True)
    parser.add_argument("--data-dir", default="data/miqp")
    parser.add_argument("--output", default=None)
    parser.add_argument("--time-limit", type=float, default=60.0)
    parser.add_argument("--process-timeout", type=float, default=120.0)
    args = parser.parse_args()

    solver = Path(args.solver).resolve()
    data_dir = Path(args.data_dir)
    instances = sorted(data_dir.glob("*.mps"))
    if not instances:
        print(f"[-] no .mps instances under {data_dir}", file=sys.stderr)
        return 1
    output = Path(args.output or
                  f"evidence/miqp01-synthetic-{date.today().isoformat()}.json")

    rows = []
    for mps in instances:
        record = run_instance(solver, mps, args.time_limit, args.process_timeout)
        rows.append(record)
        print(f"{record['instance']:<32} {str(record.get('status')):<16} "
              f"nodes={record.get('nodes_explored')} "
              f"bound={record.get('best_bound')} gap={record.get('relative_gap')}")

    by_status: dict[str, int] = {}
    for row in rows:
        key = str(row.get("status") or "NoJSON")
        by_status[key] = by_status.get(key, 0) + 1
    failures = [row["instance"] for row in rows if row.get("complete_failure")]
    artifact = {
        "record": "miqp01-synthetic",
        "date": date.today().isoformat(),
        "contract": "docs/contracts/miqp-node-bounds.md §7.8",
        "solver": str(solver),
        "solver_sha256": sha256(solver),
        "command": [str(solver), "<instance>", "--engine", "miqp",
                    "--time-limit", str(args.time_limit)],
        "time_limit_seconds": args.time_limit,
        "instances_total": len(rows),
        "status_counts": by_status,
        "complete_failures": failures,
        "note": "Statuses as measured on the checked-in synthetic convex MIQP "
                "stratum (data/miqp, generated by scripts/generators/gen_miqp01_instances.py). "
                "Separate from the linear MIP summary. No speed claim; failures stay in "
                "the denominator.",
        "results": rows,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(artifact, indent=2) + "\n", encoding="utf-8")
    print(f"[+] wrote {output} ({len(rows)} instances, {len(failures)} complete failures)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
